"""
MCP Server - Vault (shared second brain for the SOC TEAM, remote, security-only)

This is the shared Obsidian vault for the whole SOC team. It lives on a remote
Linux VM and is dedicated to cybersecurity content only - it should never hold
software-development notes.

It runs LOCALLY on each analyst's machine (stdio, like any other mcp-* server),
but it does not touch the local filesystem: every tool call opens an SSH
connection to the VM and runs the "forced command" configured in the shared
account's authorized_keys for THAT analyst's key (see
mcp-vault/agent/bin/vault-agent.py). The identity used for auditing is decided
by sshd on the server according to which key connected, not by any field sent
by this client - which is why the payload sent over stdin carries no "analyst".

Environment variables (required, no default embedded in the code - they are set
as per-user environment variables on the device by the installer, like
AZURE_TENANT_ID/CORTEX_FQDN/etc. in the rest of the stack):
  VAULT_HOST      IP/hostname of the VM
  VAULT_USER      Shared Unix account on the VM
  VAULT_SSH_KEY   Path to THIS analyst's private key (generated by the
                  installer if it does not exist)

Requiere: pip install -r requirements.txt
"""

