# ---------------------------------------------------------------------------
# call_tool - delegates everything to the remote vault-agent over SSH
# ---------------------------------------------------------------------------

@server.call_tool()
@audited("vault")
async def call_tool(name: str, arguments: dict):
    try:
        data = vault_client.call_vault(name, arguments)
        return ok(data)
    except Exception as e:
        return err(e)


async def _main():
    async with stdio_server() as (read_stream, write_stream):
        await server.run(
            read_stream,
            write_stream,
            server.create_initialization_options(),
        )

if __name__ == "__main__":
    import asyncio
    asyncio.run(_main())
